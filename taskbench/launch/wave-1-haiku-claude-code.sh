#!/usr/bin/env bash
# wave-1-haiku-claude-code.sh — Haiku 4.5 through Claude Code, on the existing subscription.
# One command, no arguments. Running it IS the approval for this batch's spend.
#
#   taskbench/launch/wave-1-haiku-claude-code.sh
#
# The cheapest arm, and the one with no gateway: it runs on the Anthropic subscription the hive
# already has, so there is no OpenRouter route to pin and no receipt recorder. Its consumption
# is whatever Claude Code's own result envelope reports — token and cache counts are the
# harness's, and the subscription means there is no per-run gateway price to report. An
# estimate from a price table would not be one, so cost stays absent rather than invented.

set -euo pipefail

# shellcheck source=taskbench/launch/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

readonly RECORD_BASE="wave-1-haiku-claude-code"
readonly MODEL_ALIAS="claude-haiku-4-5"
readonly VENDOR="anthropic"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly REPO_ROOT
readonly RECORDS_DIR="$REPO_ROOT/taskbench/records"
readonly WORK_BASE="${TASKBENCH_WORK_BASE:-$HOME/work/taskbench}"

step "The bundle under test"
need claude "the candidate and the reviewer are both Claude Code sessions"
need uv     "taskbench runs under uv"
need bwrap  "the reviewer's cold-reader sandbox needs it"
need git    "the materializer exports pre-task trees with it"

HARNESS_VERSION="$(claude_harness_version)"
readonly HARNESS_VERSION
CLAUDE_BIN="$(command -v claude)"
readonly CLAUDE_BIN

say "vendor:   $VENDOR"
say "model:    $MODEL_ALIAS   (a request; the resolved id is read back from the run's own report)"
say "harness:  $HARNESS_VERSION"
say "gateway:  none — the Anthropic subscription, direct"
say "upstream: firstParty (Anthropic); no OpenRouter preset applies to this arm"

step "Reserving a record"
read -r RECORD_ID SUPERSEDES <<<"$(reserve_record "$REPO_ROOT" "$RECORD_BASE" "$RECORDS_DIR")"
readonly RECORD_ID SUPERSEDES
WORK_ROOT="$WORK_BASE/$RECORD_ID"
readonly WORK_ROOT
say "record:   $RECORD_ID"
if [ "$SUPERSEDES" != "-" ]; then
  say "NOTE:     this supersedes $SUPERSEDES, which is kept unmodified."
  say "          A rerun must be able to name the package defect that made it necessary;"
  say "          a rerun that cannot is a model result being re-rolled."
fi
read -r RESUME_FROM RESUME_COUNT <<<"$(resume_target "$REPO_ROOT" "$RECORD_BASE" "$RECORDS_DIR")"
readonly RESUME_FROM RESUME_COUNT
if [ "$RESUME_FROM" != "-" ]; then
  say "resume:   carrying $RESUME_COUNT conclusive cell(s) forward from $(basename "$RESUME_FROM")"
fi
say "work:     $WORK_ROOT"
mkdir -p "$WORK_ROOT" "$RECORDS_DIR"

step "Generating the runner config"
CONFIG="$WORK_ROOT/runner-config.yaml"
readonly CONFIG
{
  printf '# Generated by wave-1-haiku-claude-code.sh — do not hand-edit.\n'
  printf 'agent:\n'
  printf '  argv: ["%s", "--model", "%s", "--print", "--output-format", "json",\n' \
         "$CLAUDE_BIN" "$MODEL_ALIAS"
  printf '         "--permission-mode", "auto"]\n'
  printf '  labels: {vendor: "%s", model: "%s", harness: "%s"}\n' \
         "$VENDOR" "$MODEL_ALIAS" "$HARNESS_VERSION"
  printf '  result_envelope: claude-code-json\n'
  printf '  env_passthrough: ["HOME", "PATH", "LANG", "TERM", "XDG_RUNTIME_DIR"]\n'
  printf '  cwd: code\n'
  printf '  timeout_s: 7200\n'
  printf '  prompt_mode: argv\n'
  emit_reviewer_block
  emit_sources_block "$REPO_ROOT"
} > "$CONFIG"
say "config:   $CONFIG"
say ""
say "The kickoff is the SAME fixed minimal kickoff every bundle receives, built by the runner"
say "from the frozen manifest. No wave adds harness-specific task context."

step "Smoke: one disposable read/edit/test loop on this exact bundle"
say "Same argv the batch will use, against a three-file fixture. A bundle that cannot read a"
say "file it was not given, edit a second and run the third has nothing to say about an order."
set +e
(
  cd "$REPO_ROOT" || exit 1
  uv run --frozen taskbench qualify-smoke \
    --config "$CONFIG" --bundle "haiku-claude-code" \
    --root "$WORK_ROOT/smoke" --out "$WORK_ROOT"
)
smoke_status=$?
set -e
if [ "$smoke_status" -ne 0 ]; then
  say ""
  say "The batch does NOT run. Nothing was scored and nothing was spent on the matrix."
  exit "$smoke_status"
fi

install_interrupt_trap "$RECORDS_DIR" "$RECORD_ID" "$WORK_ROOT"

step "The pause point: $FIRST_TASK first"
say "The precommitted cheapest/high-signal task runs first for every bundle. When it finishes,"
say "STOP AND LOOK before the other four. Its completion is an operator pause point — it is"
say "never permission to score a partial bundle as adequate."
say ""
say "Preflight runs first and refuses before the first model call if anything disagrees."

set +e
(
  cd "$REPO_ROOT" || exit 1
  args=(
    --config "$CONFIG" --record-id "$RECORD_ID" --work-root "$WORK_ROOT"
    --out "$RECORDS_DIR" --expect-corpus-hash "$EXPECT_CORPUS_HASH"
    --tasks "$FIRST_TASK,instrument-teeth,launch-pane-fix,ptc-revalidate,run-registration"
  )
  [ "$SUPERSEDES" != "-" ] && args+=(--supersedes "$SUPERSEDES")
  [ "$RESUME_FROM" != "-" ] && args+=(--resume-from "$RESUME_FROM")
  uv run --frozen taskbench run "${args[@]}"
)
status=$?
set -e

report_status "$status" "$RECORDS_DIR/$(date +%F)-$RECORD_ID" "$WORK_ROOT" "$REPO_ROOT"
exit "$status"
