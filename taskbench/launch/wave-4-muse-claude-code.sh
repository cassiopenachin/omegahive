#!/usr/bin/env bash
# wave-4-muse-claude-code.sh — Muse Spark 1.2 standard through Claude Code, on the same
# OpenRouter account and Anthropic Messages skin. One command, no arguments.
#
#   taskbench/launch/wave-4-muse-claude-code.sh
#
# TWO THINGS THIS ARM'S RESULT MUST CARRY, and they are written here so the report cannot
# quietly omit them:
#
#   * **The harness is a substitution, and a recorded one.** The precommitted arm was Muse Code
#     through OpenRouter. The official `0.1.0-R708.1` build is compiled without the
#     `provider-openrouter` feature and its `meta` provider requires Meta's private catalog, so
#     that arm is honestly `unreachable`. The operator selected Claude Code `2.1.232` on
#     2026-08-14 rather than pay Meta directly. Native Muse Code and Muse-through-Codex remain
#     future candidate bundles — not silent fallbacks for this one.
#   * **Claude Code gives this route a 200k effective context and 32k maximum output**, against
#     the model's advertised 1,048,576. That bounded surface is acceptable for a five-task v0
#     and must be REPORTED. It does not qualify Muse's full-context behaviour, and no claim
#     about long-context work may rest on these cells.
#
# `muse-spark-1.2-contributor` is prohibited outright and is refused by the model allowlist.

set -euo pipefail

# shellcheck source=taskbench/launch/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

readonly PRESET="omegahive-muse-spark-1-2"
readonly MODEL="meta/muse-spark-1.2@preset/omegahive-muse-spark-1-2"
readonly VENDOR="meta"
readonly UPSTREAM="meta"
readonly RECORD_BASE="wave-4-muse-claude-code"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly REPO_ROOT
readonly RECORDS_DIR="$REPO_ROOT/taskbench/records"
readonly WORK_BASE="${TASKBENCH_WORK_BASE:-$HOME/work/taskbench}"

step "The bundle under test"
need claude "this arm's harness, and the blinded reviewer"
need uv     "taskbench runs under uv"
need bwrap  "the reviewer's cold-reader sandbox needs it"
need git    "the materializer exports pre-task trees with it"

[ -n "${OPENROUTER_API_KEY:-}" ] || die "OPENROUTER_API_KEY is not exported.

  It is the operator's secret and lives outside both repositories. Export it into this shell,
  then re-run. Nothing here reads a secrets file or writes the value anywhere."

HARNESS_VERSION="$(claude_harness_version)"; readonly HARNESS_VERSION
CLAUDE_BIN="$(command -v claude)";           readonly CLAUDE_BIN

say "vendor:   $VENDOR"
say "model:    $MODEL   (standard tier; the contributor SKU is prohibited and refused)"
say "harness:  $HARNESS_VERSION   — a RECORDED substitution for the unreachable Muse Code arm"
say "gateway:  OpenRouter, Anthropic Messages skin, through the receipt recorder"
say "preset:   $PRESET   (re-fetched and hashed before the batch and every cell)"
say "upstream: $UPSTREAM only, provider fallback DISABLED"
say "context:  200k effective / 32k max output as Claude Code drives this route,"
say "          against the model's advertised 1,048,576 — report it, never present the"
say "          advertised figure as what was exercised"

step "Reserving a record"
read -r RECORD_ID SUPERSEDES <<<"$(reserve_record "$REPO_ROOT" "$RECORD_BASE" "$RECORDS_DIR")"
readonly RECORD_ID SUPERSEDES
WORK_ROOT="$WORK_BASE/$RECORD_ID"
readonly WORK_ROOT
say "record:   $RECORD_ID"
[ "$SUPERSEDES" != "-" ] && say "NOTE:     supersedes $SUPERSEDES, kept unmodified."
read -r RESUME_FROM RESUME_COUNT <<<"$(resume_target "$REPO_ROOT" "$RECORD_BASE" "$RECORDS_DIR")"
readonly RESUME_FROM RESUME_COUNT
[ "$RESUME_FROM" != "-" ] && \
  say "resume:   carrying $RESUME_COUNT conclusive cell(s) from $(basename "$RESUME_FROM")"
say "work:     $WORK_ROOT"
mkdir -p "$WORK_ROOT" "$RECORDS_DIR"

step "Generating the runner config"
CONFIG="$WORK_ROOT/runner-config.yaml"
readonly CONFIG
{
  printf '# Generated by wave-4-muse-claude-code.sh — do not hand-edit.\n'
  printf 'agent:\n'
  printf '  argv: ["%s", "--model", "%s", "--print", "--output-format", "json",\n' \
         "$CLAUDE_BIN" "$MODEL"
  printf '         "--permission-mode", "auto"]\n'
  printf '  labels: {vendor: "%s", model: "%s", harness: "%s"}\n' \
         "$VENDOR" "$MODEL" "$HARNESS_VERSION"
  printf '  result_envelope: claude-code-json\n'
  printf '  env_passthrough: ["PATH", "LANG", "TERM", "XDG_RUNTIME_DIR", "ANTHROPIC_AUTH_TOKEN"]\n'
  printf '  env:\n'
  printf '    GIT_TERMINAL_PROMPT: "0"\n'
  printf '  cwd: code\n'
  printf '  timeout_s: 7200\n'
  printf '  prompt_mode: argv\n'
  emit_reviewer_block
  emit_sources_block "$REPO_ROOT"
} > "$CONFIG"
say "config:   $CONFIG"

install_interrupt_trap "$RECORDS_DIR" "$RECORD_ID" "$WORK_ROOT"

step "The pause point: $FIRST_TASK first"
say "Same fixed order as every other bundle. Stop and look when it finishes."

set +e
(
  cd "$REPO_ROOT" || exit 1
  args=(
    --config "$CONFIG" --record-id "$RECORD_ID" --work-root "$WORK_ROOT"
    --out "$RECORDS_DIR" --preset "$PRESET"
    --expect-corpus-hash "$EXPECT_CORPUS_HASH"
    --tasks "$FIRST_TASK,instrument-teeth,launch-pane-fix,ptc-revalidate,run-registration"
  )
  [ "$SUPERSEDES" != "-" ] && args+=(--supersedes "$SUPERSEDES")
  [ "$RESUME_FROM" != "-" ] && args+=(--resume-from "$RESUME_FROM")
  uv run --frozen taskbench run-gateway "${args[@]}"
)
status=$?
set -e

RECORD_DIR="$RECORDS_DIR/$(date +%F)-$RECORD_ID"
step "Whole-record gateway totals"
( cd "$REPO_ROOT" && uv run --frozen taskbench gateway-totals "$RECORD_DIR" ) || true

report_status "$status" "$RECORD_DIR" "$WORK_ROOT" "$REPO_ROOT"
exit "$status"
